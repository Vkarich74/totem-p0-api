);
CREATE TABLE public.salon_master_services(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  salon_id integer NOT NULL REFERENCES public.salons(id),
  master_id integer NOT NULL REFERENCES public.masters(id),
  service_pk integer NOT NULL REFERENCES public.services(id),
  price integer NOT NULL CHECK(price>=0),
  duration_min integer NOT NULL CHECK(duration_min>0),
  active boolean NOT NULL DEFAULT true,
  currency_code text,
  CONSTRAINT uq_sms_unique UNIQUE(salon_id,master_id,service_pk)
);
CREATE TABLE public.us_service_price_amounts(
  salon_master_service_id integer PRIMARY KEY
    REFERENCES public.salon_master_services(id) ON DELETE RESTRICT,
  market_id bigint NOT NULL REFERENCES public.markets(id),
  amount_minor bigint NOT NULL CHECK(amount_minor BETWEEN 1 AND 99999999),
  currency_code text NOT NULL DEFAULT 'USD' CHECK(currency_code='USD'),
  price_version bigint NOT NULL DEFAULT 1 CHECK(price_version>0)
);
CREATE FUNCTION public.us_service_price_check() RETURNS trigger
LANGUAGE plpgsql AS $body$
BEGIN
  IF NOT EXISTS(
    SELECT 1 FROM public.salon_master_services sms
    JOIN public.tenant_market_settings tm ON tm.salon_id=sms.salon_id
    JOIN public.markets m ON m.id=tm.market_id
    WHERE sms.id=NEW.salon_master_service_id AND tm.market_id=NEW.market_id
      AND sms.active IS TRUE AND sms.currency_code='USD'
      AND m.code='US' AND m.country_code='US' AND m.default_currency='USD'
      AND m.active IS TRUE
  ) THEN
    RAISE EXCEPTION 'US_C11_SERVICE_MARKET_MISMATCH' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$body$;
